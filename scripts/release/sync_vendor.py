#!/usr/bin/env python
"""
Keep the web app's vendored copy of the library in sync.

webapps/model_comparisons/ ships as a standalone zip with its own copy of the
modules it needs (webapps/model_comparisons/ioos_model_comparisons/). This
copies exactly the files in vendor_manifest.txt from the top-level package —
never edit the vendored copy by hand; edit the top-level module and run this.

    python scripts/release/sync_vendor.py           # copy
    python scripts/release/sync_vendor.py --check   # CI: fail on drift

--check fails when:
  * a vendored file differs from (or is missing vs) its source,
  * the vendored directory has files the manifest doesn't list,
  * the web app (or a vendored module) imports a third-party package that
    isn't in webapps/model_comparisons/requirements.txt — the deploy that
    once produced a silent 500 on /fronts (shapely missing) is caught here.
"""

import argparse
import ast
import filecmp
import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "ioos_model_comparisons"
APP = REPO / "webapps" / "model_comparisons"
DST = APP / "ioos_model_comparisons"
MANIFEST = Path(__file__).with_name("vendor_manifest.txt")
REQUIREMENTS = APP / "requirements.txt"
KEEP = {"README.md", "VENDORED_FROM"}

# import name -> distribution name, where they differ
IMPORT_TO_DIST = {
    "yaml": "pyyaml", "dotenv": "python-dotenv", "flask_login": "flask-login",
    "bs4": "beautifulsoup4", "shapefile": "pyshp", "PIL": "pillow",
    "sklearn": "scikit-learn", "werkzeug": "flask", "jinja2": "flask",
    "bson": "pymongo", "pydantic_core": "pydantic", "dateutil": "python-dateutil",
}


def manifest_files():
    patterns = [l.strip() for l in MANIFEST.read_text().splitlines()
                if l.strip() and not l.lstrip().startswith("#")]
    files = set()
    for pat in patterns:
        hits = [p for p in SRC.glob(pat) if p.is_file()]
        if not hits:
            sys.exit(f"manifest entry matches nothing: {pat}")
        files.update(p.relative_to(SRC).as_posix() for p in hits)
    return sorted(files)


def vendored_files():
    out = set()
    for p in DST.rglob("*"):
        if p.is_file() and "__pycache__" not in p.parts and p.name not in KEEP \
                and not p.name.endswith(".pyc") and p.name != ".DS_Store":
            out.add(p.relative_to(DST).as_posix())
    return out


def _sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def sync():
    files = manifest_files()
    for rel in files:
        dst = DST / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(SRC / rel, dst)
    for rel in sorted(vendored_files() - set(files)):
        (DST / rel).unlink()
        print(f"removed stale {rel}")
    try:
        sha = subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True).stdout.strip()
    except Exception:
        sha = "unknown"
    lines = [f"# Generated by scripts/release/sync_vendor.py from git {sha}. Do not edit.",
             *(f"{_sha(SRC / rel)}  {rel}" for rel in files)]
    (DST / "VENDORED_FROM").write_text("\n".join(lines) + "\n")
    print(f"synced {len(files)} files into {DST.relative_to(REPO)}")


def _third_party_imports(paths, local):
    stdlib = set(sys.stdlib_module_names)
    found = {}
    for path in paths:
        tree = ast.parse(path.read_text(), filename=str(path))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                names = [a.name for a in node.names]
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                names = [node.module]
            else:
                continue
            for n in names:
                top = n.split(".")[0]
                if top in stdlib or top in local or top == "__future__":
                    continue
                found.setdefault(top, set()).add(path.relative_to(REPO).as_posix())
    return found


def _requirement_names():
    names = set()
    for line in REQUIREMENTS.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.add(re.split(r"[<>=!~\[; ]", line, 1)[0].lower().replace("_", "-"))
    return names


def check():
    problems = []
    files = manifest_files()
    for rel in files:
        dst = DST / rel
        if not dst.exists():
            problems.append(f"missing from vendored copy: {rel}")
        elif not filecmp.cmp(SRC / rel, dst, shallow=False):
            problems.append(f"vendored copy differs from source: {rel}")
    for rel in sorted(vendored_files() - set(files)):
        problems.append(f"vendored file not in manifest: {rel}")

    app_py = [p for p in APP.glob("*.py")] + [p for p in DST.rglob("*.py")]
    local = {p.stem for p in APP.glob("*.py")} | {"ioos_model_comparisons"}
    have = _requirement_names()
    for mod, where in sorted(_third_party_imports(app_py, local).items()):
        dist = IMPORT_TO_DIST.get(mod, mod).lower().replace("_", "-")
        if dist not in have:
            problems.append(f"'{mod}' is imported ({', '.join(sorted(where))}) but "
                            f"'{dist}' is not in {REQUIREMENTS.relative_to(REPO)}")
    if problems:
        print("vendored web app package is out of sync:\n  - " + "\n  - ".join(problems))
        print("fix: python scripts/release/sync_vendor.py  (and/or add the requirement)")
        return 1
    print(f"vendored copy matches ({len(files)} files); requirements cover all imports")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    if args.check:
        sys.exit(check())
    sync()


if __name__ == "__main__":
    main()
